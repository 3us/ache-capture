#!/bin/sh
# Builds ache-capture.exe (Windows x64) and the folder it runs from, on macOS or
# Linux, with clang and the Windows SDK as cargo-xwin / xwin downloads it.
#
#   ./build.sh            # -> dist/ache-capture/ (ache-capture.exe + the OBS files it needs)
#
# Needs: clang + lld-link + llvm-dlltool (Homebrew llvm), curl, unzip, tar,
# and an xwin sysroot (XWIN, default: cargo-xwin's cache).
set -eu

OBS_VERSION=33.0.3
OBS_ZIP_SHA256=18a68c325adbda6f6082d5281021a8d1e35a6432842800618e8690b71925c107
OBS_SRC_SHA256=784879e4ce0c5cc69a34bb6ae0ed7f0a7c5fad59950ba04c3b43614f1df41a0c

HERE=$(cd "$(dirname "$0")" && pwd)
WORK="$HERE/build"
DIST="$HERE/dist/ache-capture"
LLVM=${LLVM:-$(brew --prefix llvm 2>/dev/null || echo /usr)/bin}
XWIN=${XWIN:-$HOME/Library/Caches/cargo-xwin/xwin}
[ -d "$XWIN/crt" ] || XWIN=$HOME/.cache/cargo-xwin/xwin
[ -d "$XWIN/crt" ] || { echo "no xwin sysroot: set XWIN" >&2; exit 1; }

mkdir -p "$WORK"
fetch() { # name sha256
  if [ ! -f "$WORK/$1" ]; then
    curl -fL --proto '=https' -o "$WORK/$1.part" "https://github.com/obsproject/obs-studio/releases/download/$OBS_VERSION/$1"
    mv "$WORK/$1.part" "$WORK/$1"
  fi
  echo "$2  $WORK/$1" | shasum -a 256 -c - >/dev/null || { echo "checksum mismatch: $1" >&2; exit 1; }
}
fetch "OBS-Studio-$OBS_VERSION-Windows-x64.zip" "$OBS_ZIP_SHA256"
fetch "OBS-Studio-$OBS_VERSION-Sources.tar.gz" "$OBS_SRC_SHA256"

OBS="$WORK/obs"
SRC="$WORK/obs-studio-$OBS_VERSION-sources"
[ -d "$OBS" ] || { mkdir -p "$OBS" && unzip -q "$WORK/OBS-Studio-$OBS_VERSION-Windows-x64.zip" -d "$OBS"; }
[ -d "$SRC" ] || tar -xzf "$WORK/OBS-Studio-$OBS_VERSION-Sources.tar.gz" -C "$WORK"

# obsconfig.h is generated by OBS's CMake; ache-capture needs none of its paths.
GEN="$WORK/gen"
mkdir -p "$GEN"
printf '#pragma once\n#define OBS_RELEASE_CANDIDATE 0\n#define OBS_BETA 0\n' > "$GEN/obsconfig.h"

# Import library for obs.dll, from its export table.
"$LLVM/llvm-readobj" --coff-exports "$OBS/bin/64bit/obs.dll" | awk '/Name: /{print $2}' | grep -v '^$' > "$GEN/obs.exports"
{ echo "LIBRARY obs.dll"; echo "EXPORTS"; cat "$GEN/obs.exports"; } > "$GEN/obs.def"
"$LLVM/llvm-dlltool" -m i386:x86-64 -d "$GEN/obs.def" -l "$GEN/obs.lib"

INC="-I$SRC/libobs -I$GEN"
SYS="-isystem $XWIN/crt/include -isystem $XWIN/sdk/include/ucrt -isystem $XWIN/sdk/include/um -isystem $XWIN/sdk/include/shared"
"$LLVM/clang" --target=x86_64-pc-windows-msvc -O2 -std=c11 -fms-extensions -fms-compatibility \
  -D_CRT_SECURE_NO_WARNINGS -DWIN32_LEAN_AND_MEAN -DUNICODE -D_UNICODE \
  -Wno-microsoft-anon-tag -Wno-pragma-pack $INC $SYS \
  -c "$HERE/src/ache-capture.c" -o "$GEN/ache-capture.obj"
"${LLD_LINK:-$(command -v lld-link || echo "$LLVM/lld-link")}" /nologo /subsystem:console /out:"$GEN/ache-capture.exe" "$GEN/ache-capture.obj" "$GEN/obs.lib" \
  /libpath:"$XWIN/crt/lib/x86_64" /libpath:"$XWIN/sdk/lib/um/x86_64" /libpath:"$XWIN/sdk/lib/ucrt/x86_64" \
  libcmt.lib libucrt.lib libvcruntime.lib kernel32.lib

# The folder it runs from, laid out like OBS so libobs finds its data and plugins:
# bin/64bit/ (the exe and DLLs), data/libobs/, core/<plugin>/.
rm -rf "$DIST"
mkdir -p "$DIST/bin/64bit" "$DIST/data" "$DIST/core"
cp "$GEN/ache-capture.exe" "$DIST/bin/64bit/"
for f in obs.dll libobs-d3d11.dll libobs-winrt.dll w32-pthreads.dll zlib.dll libcurl.dll \
         avcodec-62.dll avformat-62.dll avutil-60.dll avdevice-62.dll avfilter-11.dll swresample-6.dll swscale-9.dll \
         librist.dll srt.dll libx264-164.dll datachannel.dll; do
  [ -f "$OBS/bin/64bit/$f" ] && cp "$OBS/bin/64bit/$f" "$DIST/bin/64bit/"
done
cp -R "$OBS/data/libobs" "$DIST/data/"
for m in win-capture obs-nvenc obs-ffmpeg obs-qsv11 obs-x264; do
  mkdir -p "$DIST/core/$m"
  cp "$OBS/core/$m/$m.dll" "$DIST/core/$m/"
  [ -d "$OBS/core/$m/data" ] && cp -R "$OBS/core/$m/data" "$DIST/core/$m/"
done
find "$DIST" -name '*.pdb' -delete
cp "$HERE/LICENSE" "$DIST/LICENSE.txt"
cp "$SRC/COPYING" "$DIST/OBS-COPYING.txt"
du -sh "$DIST"
echo "built $DIST"
